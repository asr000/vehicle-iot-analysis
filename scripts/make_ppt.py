def add_text(slide, left, top, width, height, lines, font_size, bold_first=False, color=GRAY):
    box = slide.shapes.add_textbox(left, top, width, height)
    tf = box.text_frame
    tf.word_wrap = True
    for i, line in enumerate(lines):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.text = line
        p.space_after = Pt(8)
        for run in p.runs:
            run.font.size = Pt(font_size)
            run.font.color.rgb = color
            run.font.name = "Microsoft YaHei"
            if bold_first and i == 0:
                run.font.bold = True
    return box


def build():
    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)
    blank = prs.slide_layouts[6]

    for idx, s in enumerate(SLIDES, 1):
        slide = prs.slides.add_slide(blank)
        add_text(slide, Inches(0.5), Inches(0.3), Inches(12.3), Inches(0.9),
                 [s["title"]], 28, bold_first=True, color=DARK)
        body_lines = ["• " + b for b in s["bullets"]]
        width = Inches(12.3) if s["image"] is None else Inches(6.7)
        add_text(slide, Inches(0.5), Inches(1.3), width, Inches(5.6), body_lines, 16)
        if s["image"]:
            path = FIG / s["image"]
            if path.exists():
                slide.shapes.add_picture(str(path), Inches(7.4), Inches(1.4), width=Inches(5.5))
        add_text(slide, Inches(12.4), Inches(7.0), Inches(0.8), Inches(0.4),
                 [str(idx)], 12, color=GRAY)
        slide.notes_slide.notes_text_frame.text = s["notes"]

    out = ROOT / "汇报.pptx"
    prs.save(out)
    print(f"PPT 已生成：{out}（{len(SLIDES)} 页）")

    lines = ["# 汇报讲稿\n", "> 与《汇报.pptx》备注内容一致，供宣读与排练使用。\n"]
    for i, s in enumerate(SLIDES, 1):
        lines.append(f"\n## 第 {i} 页　{s['title']}\n")
        lines.append(s["notes"] + "\n")
    (ROOT / "reports" / "讲稿.md").write_text("".join(lines), encoding="utf-8")
    print("讲稿已生成：reports/讲稿.md")


if __name__ == "__main__":
    build()
